const REPO_ROOT = require("path").resolve(__dirname, "..");
const SP = process.env.TEST_TMP || require("path").join(__dirname, ".tmp");
for (const d of ["", "/shots", "/smoke_v2", "/smoke_v2/shots"]) require("fs").mkdirSync(SP + d, { recursive: true });
const fs = require("fs");
const { chromium } = require("playwright-core");
const body = fs.readFileSync(REPO_ROOT + "/index.html", "utf8");
fs.writeFileSync(SP + "/page.html", '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"></head><body>' + body + "</body></html>");
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 390, height: 860 } });
  const errs = []; p.on("pageerror", e => errs.push(String(e))); p.on("console", m => { if (m.type() === "error") errs.push(m.text()); });
  await p.goto("file:///" + SP + "/page.html");
  const ok = (n, c, d) => console.log((c ? "PASS " : "FAIL ") + n + (d ? "  | " + d : ""));
  ok("reset hidden on setup", await p.isHidden("#mast-reset"));
  await p.selectOption("#riding-select", "SRF");
  ok("riding picked", (await p.textContent("#riding-name")) === "Surrey-Fleetwood");
  await p.click('label[for="count-2"]');
  await p.fill("#name-0", "Dad");
  await p.click("#start-btn");
  await p.click(".opt >> nth=0");
  await p.click("#next-btn");
  ok("reset visible in quiz", await p.isVisible("#mast-reset"));
  await p.screenshot({ path: SP + "/reset_quiz390.png" });
  await p.click("#mast-reset");
  ok("dialog open", await p.isVisible("#reset-yes"), await p.textContent("#reset-title"));
  await p.click("#reset-no");
  ok("keep keeps quiz", await p.isVisible("#q-title"));
  await p.click("#mast-reset"); await p.click("#reset-yes");
  const st = await p.evaluate(() => ({ ls: localStorage.getItem("bcvh2026:v1"), setup: !!document.getElementById("setup-title"), name: document.getElementById("name-0").value, count: document.querySelector('input[name="count"]:checked').value, riding: BCVH.getState().riding, picker: !!document.getElementById("riding-select"), chip: document.getElementById("mast-riding").hidden }));
  ok("back on setup, cleared (riding too)", st.setup && st.name === "" && st.count === "1" && st.riding === null && st.picker && st.chip, JSON.stringify(st));
  ok("reset hidden again", await p.isHidden("#mast-reset"));
  // results toolbar reset
  await p.evaluate(() => { const s = BCVH.getState(); s.phase = "results"; s.people[0].answers = { q_housing: { choice: "a", importance: "medium" } }; BCVH.setState(s); });
  ok("toolbar reset on results", await p.isVisible("#tb-reset"));
  await p.click("#tb-reset"); await p.click("#reset-yes");
  ok("results -> setup", await p.isVisible("#setup-title"));
  ok("no errors", errs.length === 0, errs.join(" ; "));
  await b.close();
})();
